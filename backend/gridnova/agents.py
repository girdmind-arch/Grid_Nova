# ---------- response-time model (simulated minutes) ----------
# GridNova: detect (sensor latency) + analyse (twin runs the search needed) + act (switching
# operations of the chosen plan). The analysis part is measured from the actual search, so a
# Critic memory that shortens the search really shortens the response.
DETECT_MIN = {"cloud_cover": 0.8, "heatwave": 1.0, "line_failure": 0.6, "grid_outage": 0.4}
TWIN_RUN_MIN = 0.05  # ~3 s per twin run on the site controller
SWITCH_OP_MIN = 1.5  # one remote switching operation (open / close a switch), incl. confirmation
SETPOINT_MIN = 0.3  # a battery or HVAC setpoint change
# The no-AI baseline: an operator notices the alarm, diagnoses by phone and switches by hand.
MANUAL_MIN = {"cloud_cover": 9.0, "heatwave": 12.0, "line_failure": 21.0, "grid_outage": 14.0}
# Kept for older imports (evaluation.py, tests): the baseline part of the old fixed model.
RESPONSE_MODEL = {t: {"manual": (m / 3, m / 3, m / 3)} for t, m in MANUAL_MIN.items()}


def manual_minutes(fault_type: str, severity: int) -> float:
    return round(MANUAL_MIN[fault_type] * (0.7 + 0.1 * severity), 1)


def fmt_kw(kw: float) -> str:
    return f"{round(kw):,} kW"


def fmt_inr(inr: float) -> str:
    return f"₹{round(inr):,}"


def fmt_hours(h: float) -> str:
    total = max(0, round(h * 60))
    hh, mm = divmod(total, 60)
    return f"{hh} h {mm} min" if hh else f"{mm} min"


def fmt_hhmm(hour: float) -> str:
    total = int(round(hour * 60)) % (24 * 60)
    return f"{total // 60:02d}:{total % 60:02d}"


# ---------- Goal ----------
@dataclass
class Goal:
    text: str = "Keep labs at full power and keep tonight's bill low."
    comfort_weight: float = 150.0  # ₹ per comfort percentage point
    reserve_floor_pct: float = c.BATTERY_FLOOR_PCT

    @staticmethod
    def parse(text: str) -> "Goal":
        t = text.lower()
        g = Goal(text=text.strip())
        notes = []
        if any(w in t for w in ("storm", "reserve", "backup", "outage")):
            g.reserve_floor_pct = 60.0
            notes.append("keep the battery above 60% as an outage reserve")
        elif any(w in t for w in ("battery health", "deep discharge", "protect battery", "battery life")):
            g.reserve_floor_pct = 40.0
            notes.append("keep the battery above 40% to avoid deep discharge")
        if any(w in t for w in ("comfort", "cool", "hot", "students")):
            g.comfort_weight = 400.0
            notes.append("avoid trimming hostel cooling")
        elif any(w in t for w in ("cost", "bill", "cheap", "save", "money")):
            g.comfort_weight = 60.0
            notes.append("accept small comfort trade-offs to cut cost")
        g._notes = notes  # type: ignore[attr-defined]
        return g

    def interpretation(self) -> str:
        notes = getattr(self, "_notes", [])
        how = "; ".join(notes) if notes else "balance cost and comfort"
        return (
            f'Understood. I\'ll prioritise "{self.text}": {how}. '
            f"Labs keep full power and the battery stays between {round(self.reserve_floor_pct)}% and 90%."
        )


# ---------- Plans in the twin ----------
@dataclass
class Candidate:
    id: str
    title: str
    summary: str
    actions: list[str]
    policy: Policy
    tot: Totals = field(default_factory=Totals)
    end_soc: float = 0.0
    score: float = 0.0
    checks: list[tuple[str, bool, str]] = field(default_factory=list)
    needs_approval: bool = False
    start_soc: float = 0.0
    # The day's highest import is set by the evening peak; only going above it adds demand charge.
    peak_ref_kw: float = 0.0
    params: dict = field(default_factory=dict)

    @property
    def comfort(self) -> int:
        if self.tot.requested_kwh <= 0:
            return 100
        return int(min(100, round(self.tot.served_kwh / self.tot.requested_kwh * 100)))

    @property
    def cost(self) -> float:
        # Energy + penalties over the horizon + the day's demand charge on peak import,
        # minus the value of any change in stored battery energy.
        stored = (self.end_soc - self.start_soc) / 100 * c.BATTERY_CAPACITY_KWH * STORED_VALUE_INR_PER_KWH
        demand_kw = max(self.tot.max_import_kw, self.peak_ref_kw)
        return self.tot.cost_inr + demand_kw * c.DEMAND_CHARGE_INR_PER_KW_DAY - stored

    @property
    def passes(self) -> bool:
        return all(ok for _, ok, _ in self.checks)

    @property
    def risk(self) -> str:
        failed = [rid for rid, ok, _ in self.checks if not ok]
        if failed:
            return "high"
        if self.needs_approval or self.comfort < 80:
            return "medium"
        return "low"


def _merge(t1: Totals, t2: Totals) -> Totals:
    return Totals(
        energy_cost_inr=t1.energy_cost_inr + t2.energy_cost_inr,
        penalty_inr=t1.penalty_inr + t2.penalty_inr,
        max_import_kw=max(t1.max_import_kw, t2.max_import_kw),
        unserved_kwh=t1.unserved_kwh + t2.unserved_kwh,
        min_soc_pct=min(t1.min_soc_pct, t2.min_soc_pct),
        max_soc_pct=max(t1.max_soc_pct, t2.max_soc_pct),
        max_feeder_ratio=max(t1.max_feeder_ratio, t2.max_feeder_ratio),
        labs_unpowered=t1.labs_unpowered or t2.labs_unpowered,
        served_kwh=t1.served_kwh + t2.served_kwh,
        requested_kwh=t1.requested_kwh + t2.requested_kwh,
        dark_kwh=t1.dark_kwh + t2.dark_kwh,
    )


def run_twin(grid: LiveGrid, fault: Fault | None, pol: Policy, dt_min: float = 2.0) -> tuple[Totals, float]:
    """Simulates now -> end of the period with live weather. The fault lasts its duration, then clears."""
    start = grid.hour()
    soc = grid.battery.soc_pct
    end = horizon_end(start)
    normal_cond = grid.conditions(None)
    if fault:
        fault_end = min(end, start + fault.duration_min / 60)
        bat, tot1, _ = simulate(start, fault_end, grid.conditions(fault), pol, soc, dt_min=dt_min)
        if fault_end < end:
            normal = replace(pol, bridge_solar_gap=False, extra_discharge_kw=0.0)
            bat2, tot2, _ = simulate(fault_end, end, normal_cond, normal, bat.soc_pct, dt_min=dt_min)
            return _merge(tot1, tot2), bat2.soc_pct
        return tot1, bat.soc_pct
    bat, tot, _ = simulate(start, end, normal_cond, pol, soc, dt_min=dt_min)
    return tot, bat.soc_pct


def guardrail(cand: Candidate, fault: Fault | None, floor: float) -> list[tuple[str, bool, str]]:
    t = cand.tot
    outage = bool(fault and fault.type == "grid_outage")
    checks = [
        ("G1", not t.labs_unpowered, "Labs keep full power." if not t.labs_unpowered else "A lab would lose power."),
        (
            "G2",
            t.min_soc_pct >= floor - 0.5 and t.max_soc_pct <= c.BATTERY_CEIL_PCT + 0.5,
            f"Battery stays above {round(floor)}%." if t.min_soc_pct >= floor - 0.5 else f"Battery would fall to {round(t.min_soc_pct)}%.",
        ),
        (
            "G3",
            t.max_feeder_ratio <= c.FEEDER_LIMIT + 1e-6,
            f"Feeders peak at {round(t.max_feeder_ratio * 100)}% loading."
            if t.max_feeder_ratio <= c.FEEDER_LIMIT + 1e-6
            else f"A feeder would reach {round(t.max_feeder_ratio * 100)}% loading.",
        ),
        (
            "G4",
            t.max_import_kw <= c.CONTRACT_LIMIT_KW,
            f"Grid import peaks at {fmt_kw(t.max_import_kw)}, under the 1,600 kW limit."
            if t.max_import_kw <= c.CONTRACT_LIMIT_KW
            else f"Grid import would reach {fmt_kw(t.max_import_kw)}, over the 1,600 kW limit.",
        ),
        (
            "G5",
            outage or cand.comfort >= 90,
            "Hostel cooling changes stay within 1°C." if outage or cand.comfort >= 90 else "Hostels would get too warm.",
        ),
    ]
    return checks


def score(cand: Candidate, goal: Goal) -> float:
    penalty = 0 if cand.passes else 1e9
    return cand.cost + (100 - cand.comfort) * goal.comfort_weight + cand.tot.dark_kwh * VOLL_INR_PER_KWH + penalty


def _strategy_of(cand: Candidate) -> str:
    """What kind of plan this is, so the runner-up shown next to the winner is a real alternative."""
    p = cand.params
    bits = [p.get("battery", "cap")]
    if "reroute" in p:
        bits.append("reroute" if (cand.policy.reroute_fraction or 0) > 0.02 else "wait")
    if "hostel_level" in p:
        bits.append("hostels-on" if cand.policy.outage_hostel_level > 0.02 else "hostels-off")
    return "/".join(bits)


# ---------- The Orchestrator ----------
class Orchestrator:
    def __init__(self, grid: LiveGrid, memory: Memory):
        self.grid = grid
        self.memory = memory
        self.plans = PlanMemory()  # the Critic's experience
        self.goal = Goal()
        self.decisions: list[dict] = []  # newest first
        self.pending: dict[str, dict] = {}  # decision id -> context awaiting approval
        self.run_counts: dict[str, int] = {}
        self.last_incident: dict[str, str] = {}
        self.counter = 140
        self._lock = threading.RLock()
        self._last_routine: dict | None = None
        self._last_observed_hour: int | None = None
        self._outage_runtimes: dict[float, float] = {}
        self._seed()

    # ----- helpers -----
    def _next_id(self) -> str:
        self.counter += 1
        return f"dec-{self.counter:04d}"

    def _abs_hour(self) -> int:
        """Hours since 1 Jan 2026 on the sim clock (keeps counting across midnights)."""
        from datetime import datetime

        from .grid import IST

        epoch = datetime(2026, 1, 1, tzinfo=IST)
        return int((self.grid.day - epoch).total_seconds() // 3600 + math.floor(self.grid.hour()))

    def _controller_factory(self):
        """The Planner's learned battery policy, fed by the Forecaster's rolling forecasts."""
        if ml.PLANNER_Q is None:
            return None
        g = self.grid
        cond = g.conditions(None)
        peak = g.totals.max_import_kw
        return lambda: ml.PLANNER_Q.controller(rolling_ahead(ml.FORECASTER, cond), peak_so_far=peak)

    def _forecast(self) -> list[tuple[float, float]]:
        """The Forecaster's learned demand forecast for the next 12 hours."""
        g = self.grid
        snap = g.snapshot()
        return demand_forecast(ml.FORECASTER, g.conditions(None), g.hour(), snap.demand_kw)

    def _plan_json(self, cand: Candidate, pid: str) -> dict:
        return {
            "id": pid,
            "title": cand.title,
            "summary": cand.summary,
            "costInr": round(cand.cost),
            "risk": cand.risk,
            "comfortPct": cand.comfort,
            "actions": cand.actions,
        }

    def _search(self, fault: Fault | None, kind: str, seeds: list[dict], rng_key: str, max_rounds: int = 6, batch: int = 16):
        """Runs the Planner's search. Returns (ranked candidates, stats, recalled memory or None)."""
        g = self.grid
        floor = self.goal.reserve_floor_pct
        ref = g.policy.peak_target_kw or 0.0
        base = replace(g.default_policy(), reserve_floor_pct=floor, peak_target_kw=g.policy.peak_target_kw,
                       reroute_fraction=None, outage_hostel_level=0.0)
        factory = self._controller_factory()
        levers = levers_for(fault, g, factory is not None)
        soc0 = g.battery.soc_pct
        temp = g.environment()["temperatureC"]
        feats = situation_features(fault, g.hour(), soc0, temp)
        recalled = self.plans.recall(kind, feats)
        if recalled:
            seeds = [recalled["params"], *seeds]

        def evaluate(params: dict, dt: float = 2.0) -> Candidate:
            pol = to_policy(params, base, factory)
            title, actions = summarise_plan(params, pol, fault)
            cand = Candidate("?", title, "", actions, pol, params=dict(params))
            cand.start_soc, cand.peak_ref_kw = soc0, ref
            cand.tot, cand.end_soc = run_twin(g, fault, pol, dt_min=dt)
            cand.checks = guardrail(cand, fault, floor)
            if fault is not None and fault.type == "grid_outage" and pol.outage_hostel_level > 0.02:
                cand.needs_approval = True  # G6: restoring hostels on a failing grid affects ~2,000 students
            cand.score = score(cand, self.goal)
            return cand

        rng = np.random.default_rng(zlib.crc32(rng_key.encode()))
        tried, stats = cross_entropy_search(levers, evaluate, rng, seeds, batch=batch, max_rounds=max_rounds,
                                            seeded_from=recalled["source"] if recalled else None)
        ranked = [cand for _, cand in tried]
        best = ranked[0]
        # The runner-up shown next to the winner: the best safe plan of a different kind.
        alt = next((x for x in ranked[1:] if _strategy_of(x) != _strategy_of(best) and x.passes), None) or \
            next((x for x in ranked[1:] if x.title != best.title), ranked[min(1, len(ranked) - 1)])
        learned = next((x for x in ranked if x.params.get("battery") == "learned"), None)
        return best, alt, stats, recalled, feats, learned, len(levers)

    def _plan_detail(self, best: Candidate, alt: Candidate, stats, learned: Candidate | None, n_levers: int) -> str:
        parts = [f"Best: {best.title.lower()}, {fmt_inr(best.cost)}, {best.comfort}% comfort.",
                 f"Runner-up: {alt.title.lower()}, {fmt_inr(alt.cost)}."]
        if learned is not None and learned.params.get("battery") == "learned":
            gap = learned.cost - best.cost
            if best.params.get("battery") == "learned":
                parts.append("The learned RL battery policy won.")
            elif learned.passes:
                parts.append(f"Learned RL battery policy: {fmt_inr(learned.cost)} ({fmt_inr(gap)} behind the winner).")
            else:
                parts.append("The learned RL battery policy was ruled out by a guardrail here.")
        if stats.history:
            parts.append(f"Search over {n_levers} levers; best safe plan by round: " + " → ".join(fmt_inr(h) for h in stats.history) + ".")
        return " ".join(parts)

    def _plan_summary(self, stats, horizon: str) -> str:
        text = f"Searched {stats.twin_runs} plans in the digital twin up to {horizon} ({stats.rounds} round{'s' if stats.rounds != 1 else ''}"
        text += f", {stats.rejected} ruled out by guardrails)." if stats.rejected else ")."
        if stats.seeded_from:
            text += f" Started from the plan that worked in {stats.seeded_from}."
        return text

    def _safety_summary(self, chosen: Candidate, other: Candidate) -> str:
        notes = [msg for _, ok, msg in chosen.checks if ok][:2]
        failed_other = [f"{rid}" for rid, ok, _ in other.checks if not ok]
        text = "The chosen plan passes all rules. " + " ".join(notes)
        if failed_other:
            text += f" The runner-up breaks {', '.join(failed_other)}."
        if chosen.needs_approval:
            text += " High-impact: needs operator approval (G6)."
        return text.strip()

    def _reason(self, chosen: Candidate, other: Candidate) -> str:
        diff = other.cost - chosen.cost
        parts = []
        dark_gap = other.tot.dark_kwh - chosen.tot.dark_kwh
        if dark_gap > 1:
            parts.append(f"It keeps power on where the runner-up would leave {round(dark_gap):,} kWh of demand in the dark")
        if not other.passes:
            broken = [msg for _, ok, msg in other.checks if not ok]
            parts.append(f"the runner-up is ruled out: {broken[0].lower()}")
        if diff > 0:
            parts.append(f"it costs {fmt_inr(diff)} less in the twin")
        elif diff < 0 and dark_gap <= 1:
            parts.append(f"it costs {fmt_inr(-diff)} more but keeps {chosen.comfort}% comfort vs {other.comfort}%")
        elif diff < 0:
            parts.append(f"for {fmt_inr(-diff)} more")
        if chosen.comfort < 100 and diff >= 0:
            parts.append(f"with {chosen.comfort}% comfort")
        text = ", ".join(parts) or "it scores best for the current goal"
        return f"{chosen.title}: {text}."

    def _explain(self, chosen: Candidate, fault: Fault | None) -> str:
        """'Why did you do that?' in plain words, built from the chosen plan's actual levers."""
        p, pol = chosen.params, chosen.policy
        bits = []
        if fault is not None and fault.type == "grid_outage":
            lvl = pol.outage_hostel_level
            bits.append("The main grid is down, so the campus runs on its own solar and battery. Labs keep full power.")
            bits.append(f"Hostels get {round(lvl * 100)}% power, a level the twin showed the battery can sustain."
                        if lvl > 0.02 else "Hostels stay off so the battery lasts as long as possible.")
        elif fault is not None and fault.type == "line_failure":
            frac = pol.reroute_fraction or 0
            name = c.ZONE_BY_ID[fault.target_zone_id or "hostel-gh1"].name
            bits.append(f"A cable fault cut power to {name}. The damaged feeder is isolated so it is safe.")
            bits.append(f"{name} is fed through feeder F2 at {round(frac * 100)}%, the most the twin found F2 can carry under its 90% limit."
                        if frac > 0.02 else f"No safe reroute was found, so {name} waits for the repair crew.")
        if p.get("battery") == "learned" and not (fault and fault.type == "grid_outage"):
            bits.append("The battery is run by the Planner's learned policy, which it trained on 40,000 simulated days.")
        elif pol.peak_target_kw and not (fault and fault.type == "grid_outage"):
            bits.append(
                f"The evening grid-import cap is about {fmt_kw(pol.peak_target_kw)}; "
                "the battery discharges only if needed to stay under it."
            )
        if pol.bridge_solar_gap:
            bits.append("While it is cloudy the battery covers the missing solar instead of buying it at a high rate.")
        if pol.extra_discharge_kw > 20 and p.get("battery") != "learned":
            bits.append(f"The battery adds {fmt_kw(pol.extra_discharge_kw)} to cover the extra load.")
        if pol.precool:
            bits.append("Hostels pre-cool slightly before the peak and then run 1°C warmer, which most people do not notice.")
        bits.append(f"In the digital twin this came out {fmt_inr(chosen.cost)} with {chosen.comfort}% comfort, the best of the plans tested.")
        return " ".join(bits)

    # ----- seed trace -----
    def _seed(self):
        """The decision the agents made just before the page opened, computed for real."""
        self.decisions.append(self._routine_decision(started_hour=self.grid.hour() - 8 / 60))

    # ----- routine operation (no fault) -----
    def _evening_peak(self) -> tuple[float, float]:
        """(kW, hour) of the next evening peak according to the Forecaster's learned model."""
        g = self.grid
        now = g.hour()
        pts = self._forecast()
        day = now - (now % 24)
        lo = day + 17 if now % 24 < 22 else day + 41
        window = [(kw, h) for h, kw in pts if lo <= h <= lo + 5]
        if window:
            return max(window)
        kw, h = max((kw, h) for h, kw in pts)
        return kw, h

    def _observe_weather(self) -> str:
        env = self.grid.environment()
        solar = fmt_kw(self.grid.snapshot().solar_kw)
        battery = f"Battery at {round(self.grid.battery.soc_pct)}%."
        if env["weatherSource"] == "open-meteo":
            cloud = f", {env['cloudPct']}% cloud" if env["cloudPct"] else ""
            return f"Live weather: {env['temperatureC']:.0f}°C in {env['location']}{cloud}. Solar {solar}. {battery}"
        return f"Typical hot day ({env['temperatureC']:.0f}°C; live weather unavailable). Solar {solar}. {battery}"

    def _forecaster_note(self) -> str:
        f = ml.METRICS.get("forecaster") if ml.FORECASTER is not None else None
        if not f:
            return "No trained forecast model loaded: using a typical-day profile."
        note = f"Learned forecast (neural network, held-out error ±{f['maeKw']:.0f} kW)."
        if ml.FORECASTER.online_updates:
            note += f" It has learned from {ml.FORECASTER.online_updates} live hour{'s' if ml.FORECASTER.online_updates != 1 else ''} so far."
        return note

    def _routine_decision(self, started_hour: float | None = None, apply: bool = True) -> dict:
        g = self.grid
        now = g.hour()
        h = now if started_hour is None else started_hour
        period = period_of(now)
        g.policy.reserve_floor_pct = self.goal.reserve_floor_pct
        target = g._evening_target(now, g.battery.soc_pct, g.conditions(None))
        g.policy.peak_target_kw = target
        peak_kw, peak_hour = self._evening_peak()
        rate = c.tariff_at(19).rate
        horizon = fmt_hhmm(horizon_end(now))
        # Starting points for the search: the battery-sized cap from the twin, an idle battery,
        # and the learned policy. The search moves on from there.
        seeds = [{"battery": "cap", "cap_kw": target, "precool": True, "hvac_trim": True, "extra_kw": 0.0},
                 {"battery": "idle", "cap_kw": target, "precool": False, "hvac_trim": True, "extra_kw": 0.0}]
        if ml.PLANNER_Q is not None:
            seeds.append({"battery": "learned", "cap_kw": target, "precool": True, "hvac_trim": True, "extra_kw": 0.0})
        best, alt, stats, recalled, feats, learned, n_levers = self._search(
            None, f"routine-{period}", seeds, f"routine-{self.counter}", max_rounds=4, batch=10)
        if apply:
            g.apply_policy(best.policy, mitigated=False)
        self.plans.store(f"routine-{period}", feats, best.params, best.score, f"the {period} plan of {fmt_hhmm(now)}",
                         f"{best.title} ({fmt_inr(best.cost)})")

        if period == "night":
            title, trigger = "Plan the night", "Off-peak tariff until 06:00; tomorrow's evening peak needs a charged battery."
            reason_line = f"Off-peak power costs ₹{c.TARIFF['off-peak'].rate:.2f}/kWh; the same energy saves ₹{rate:.2f}/kWh in tomorrow's peak."
        elif period == "day":
            title, trigger = "Plan the day", f"Demand will reach {fmt_kw(peak_kw)} around {fmt_hhmm(peak_hour)} when power costs ₹{rate:.2f}/kWh."
            reason_line = f"Daytime power costs ₹{c.TARIFF['normal'].rate:.2f}/kWh; evening power costs ₹{rate:.2f}/kWh plus the demand charge."
        else:
            title = "Manage the evening peak" if now % 24 >= 17 else "Prepare for the evening peak"
            trigger = f"Demand will reach {fmt_kw(peak_kw)} around {fmt_hhmm(peak_hour)} while the tariff is ₹{rate:.2f}/kWh."
            reason_line = f"Peak-rate power costs ₹{rate:.2f}/kWh vs ₹{c.TARIFF['off-peak'].rate:.2f} off-peak, and the day's highest import sets the demand charge."

        saving = alt.cost - best.cost
        when = iso(g.at(h))
        self._last_routine = {"period": period, "target": target, "hour": now, "temp": g.environment()["temperatureC"],
                              "title": best.title}
        decision = {
            "id": self._next_id(),
            "startedAt": when,
            "title": title,
            "trigger": trigger,
            "steps": [
                {"id": "s1", "kind": "observe", "agent": "forecaster", "at": when, "summary": self._observe_weather(),
                 "detail": f"Next evening peak: {fmt_kw(peak_kw)} around {fmt_hhmm(peak_hour)}. {self._forecaster_note()}"},
                {"id": "s2", "kind": "reason", "agent": "orchestrator", "at": when, "summary": reason_line},
                {"id": "s3", "kind": "plan", "agent": "planner", "at": when, "summary": self._plan_summary(stats, horizon),
                 "detail": self._plan_detail(best, alt, stats, learned, n_levers)},
                {"id": "s4", "kind": "safety", "agent": "guardrail", "at": when, "summary": self._safety_summary(best, alt)},
                {"id": "s5", "kind": "act", "agent": "orchestrator", "at": when, "summary": f"Applied: {best.actions[0]}."},
                {"id": "s6", "kind": "result", "agent": "critic", "at": when,
                 "summary": f"Projected {fmt_inr(saving)} better than the runner-up by {horizon}. Plan stored in memory."
                 if saving > 0 else "The two best plans come out about the same. Plan stored in memory."},
            ],
            "plans": [self._plan_json(alt, "A"), self._plan_json(best, "B")],
            "chosenPlanId": "B",
            "chosenReason": self._reason(best, alt),
            "explanation": self._explain(best, None),
            "search": self._search_json(stats, learned),
        }
        if recalled:
            decision["usedMemory"] = {"incidentId": recalled["source"], "summary": recalled["note"]}
        return decision

    @staticmethod
    def _search_json(stats, learned: Candidate | None) -> dict:
        out = {"twinRuns": stats.twin_runs, "rounds": stats.rounds, "rejected": stats.rejected,
               "bestByRound": stats.history, "seededFrom": stats.seeded_from}
        if learned is not None:
            out["learnedPolicyCostInr"] = round(learned.cost)
        return out

    # ----- scenarios -----
    def _scenario_context(self, fault: Fault) -> tuple[str, str, str]:
        """(title, trigger, what was observed): what the sensors and agents can see, computed now."""
        g = self.grid
        cond = g.conditions(fault)
        snap = g.snapshot()
        if fault.type == "cloud_cover":
            gap = cond.solar_and_temp(g.hour())[0] * (1 - cond.solar_factor)
            return ("Cover the solar dip", "Solar output dropped sharply as clouds moved over the campus.",
                    f"Solar fell by {fmt_kw(gap)}. Clouds expected for ~{fault.duration_min} min.")
        if fault.type == "heatwave":
            return ("Absorb the heatwave load", "The temperature jumped and hostel cooling demand is climbing.",
                    f"Hostel demand up {round(0.04 * fault.severity * 100)}% as ACs ramp up. Campus load now {fmt_kw(snap.demand_kw)}.")
        if fault.type == "line_failure":
            zone = c.ZONE_BY_ID[fault.target_zone_id or "hostel-gh1"]
            return (f"Isolate the fault and restore {zone.name}", f"Feeder F3 tripped. {zone.name} lost power.",
                    f"Feeder F3 tripped near {zone.name}. Tie switch T2-3 to feeder F2 is available.")
        if fault.origin == "rig":
            return ("Island the campus on battery",
                    "The tabletop rig reported its wall adapter (the rig's \"grid\") stopped supplying, so the campus grid outage started.",
                    f"Rig: {fault.note or 'adapter not supplying'}. Campus running on solar and battery ({round(g.battery.soc_pct)}%).")
        return ("Island the campus on battery", "The main grid supply from the UPPCL substation was lost.",
                f"Grid voltage lost. Campus running on solar and battery ({round(g.battery.soc_pct)}%).")

    def _scenario_seeds(self, fault: Fault) -> list[dict]:
        """First guesses (the search moves on from them): today's plan, plus 'do everything' for the fault."""
        g = self.grid
        base = {"battery": "cap", "cap_kw": g.policy.peak_target_kw or 1300.0, "precool": True, "hvac_trim": True, "extra_kw": 0.0}
        if fault.type == "cloud_cover":
            return [dict(base, bridge=True), dict(base, bridge=False)]
        if fault.type == "heatwave":
            return [dict(base, extra_kw=150.0), base]
        if fault.type == "line_failure":
            return [dict(base, reroute=1.0), dict(base, reroute=0.0)]
        return [dict(base, hostel_level=0.6), dict(base, hostel_level=0.0)]

    def _runtime_hours(self, pol: Policy) -> float:
        """How long the battery carries an islanded campus before reaching its floor."""
        g = self.grid
        start = g.hour()
        soc = g.battery.soc_pct
        cond = replace(g.conditions(None), outage=True)
        hrs = 0.0
        from .simulator import Battery, step

        bat = Battery(soc)
        tot = Totals()
        floor_pol = replace(pol, reserve_floor_pct=c.BATTERY_FLOOR_PCT)
        while hrs < 8 and bat.soc_pct > c.BATTERY_FLOOR_PCT + 0.05:
            r = step(bat, tot, start + hrs, 1 / 60, cond, floor_pol)
            if r.unserved_kw > 1:
                break
            hrs += 1 / 60
        return hrs

    @staticmethod
    def _act_minutes(fault: Fault, chosen: Candidate) -> float:
        pol = chosen.policy
        ops = 0.0
        if fault.type == "line_failure" and (pol.reroute_fraction or 0) > 0.02:
            ops += 2 * SWITCH_OP_MIN  # open S3, close T2-3
        if fault.type == "grid_outage":
            ops += SWITCH_OP_MIN + (SWITCH_OP_MIN if pol.outage_hostel_level > 0.02 else 0.0)  # island, restore hostels
        ops += SETPOINT_MIN  # battery setpoint
        if pol.precool or pol.extra_discharge_kw > 20:
            ops += SETPOINT_MIN
        return ops

    def _scenario_decision(self, fault: Fault) -> dict:
        g = self.grid
        self.run_counts[fault.type] = self.run_counts.get(fault.type, 0) + 1
        run = self.run_counts[fault.type]
        title, trigger, observed = self._scenario_context(fault)
        best, alt, stats, recalled, feats, learned, n_levers = self._search(
            fault, fault.type, self._scenario_seeds(fault), f"{fault.incident_id}-{run}")

        detect = round(DETECT_MIN[fault.type] * (0.7 + 0.1 * fault.severity), 1)
        analyse = round(stats.twin_runs * TWIN_RUN_MIN, 1)
        act = round(self._act_minutes(fault, best), 1)
        gm_min = round(detect + analyse + act, 1)
        base_min = manual_minutes(fault.type, fault.severity)
        when = iso(g.now())
        agent_observe = {"cloud_cover": "forecaster", "heatwave": "zone", "line_failure": "fault", "grid_outage": "fault"}[fault.type]

        lesson = (f"{GUARDRAIL_FREE_TITLE(best.title)} worked best at severity {fault.severity}, "
                  f"{fmt_hhmm(g.hour())}, battery {round(g.battery.soc_pct)}% ({fmt_inr(best.cost)} in the twin).")
        reason_detail = (f"Memory: {recalled['source']} was a similar situation ({recalled['note']}). Searched around that plan first."
                         if recalled else "No similar situation in memory yet: searching from scratch.")
        steps = [
            {"id": "s1", "kind": "observe", "agent": agent_observe, "at": when, "summary": observed,
             "detail": f"Detected in {detect:.1f} min of simulated time."},
            {"id": "s2", "kind": "reason", "agent": "orchestrator", "at": when, "summary": self._reason(best, alt), "detail": reason_detail},
            {"id": "s3", "kind": "plan", "agent": "planner", "at": when,
             "summary": self._plan_summary(stats, fmt_hhmm(horizon_end(g.hour()))) + f" {analyse:.1f} min of analysis.",
             "detail": self._plan_detail(best, alt, stats, learned, n_levers)},
            {"id": "s4", "kind": "safety", "agent": "guardrail", "at": when, "summary": self._safety_summary(best, alt)},
        ]

        outcome = {"run": run, "recoveryMin": gm_min, "baselineMin": base_min,
                   "breakdown": {"detectMin": detect, "analyseMin": analyse, "actMin": act, "twinRuns": stats.twin_runs}}
        if recalled:
            outcome["lessonApplied"] = recalled["note"]
        else:
            outcome["lessonLearned"] = lesson
        decision = {
            "id": f"dec-{fault.incident_id}",
            "incidentId": fault.incident_id,
            "startedAt": when,
            "title": f"{title} (run {run})" if run > 1 else title,
            "trigger": trigger,
            "steps": steps,
            "plans": [self._plan_json(alt, "A"), self._plan_json(best, "B")],
            "chosenPlanId": "B",
            "chosenReason": self._reason(best, alt),
            "explanation": self._explain(best, fault),
            "outcome": outcome,
            "search": self._search_json(stats, learned),
        }
        if recalled:  # only when a remembered plan really seeded the search
            decision["usedMemory"] = {"incidentId": recalled["source"], "summary": recalled["note"]}
        self.plans.store(fault.type, feats, best.params, best.score, fault.incident_id, lesson)
        self.last_incident[fault.type] = fault.incident_id

        if best.needs_approval:
            lvl = round(best.policy.outage_hostel_level, 2)
            options = sorted({lvl, *(round(lvl + d, 2) for d in (-0.1, 0.1) if 0.1 <= lvl + d <= 0.9)})
            self._outage_runtimes = {o: self._runtime_hours(replace(best.policy, outage_hostel_level=o)) for o in options}
            decision["approval"] = {
                "status": "pending",
                "request": f"Restore hostels at {round(lvl * 100)}% power from the battery.",
                "risk": f"If the outage lasts longer than ~{fmt_hours(self._outage_runtimes[lvl])}, the battery reaches its 20% floor and hostels must go off.",
                "modifyOptions": [
                    {"id": str(o), "label": f"{round(o * 100)}%: battery lasts ~{fmt_hours(self._outage_runtimes[o])}"
                     + (" (recommended)" if o == lvl else "")}
                    for o in options
                ],
            }
            self.pending[decision["id"]] = {"fault": fault, "chosen": best}
        else:
            g.apply_policy(best.policy, mitigated=True)
            decision["steps"] += self._final_steps(fault, best, when)
            self.memory.record(fault, decision)
        return decision

    def _final_steps(self, fault: Fault, chosen: Candidate, when: str) -> list[dict]:
        snap = self.grid.snapshot()
        agent_act = "fault" if fault.type == "line_failure" else "orchestrator"
        act = "Applied: " + "; ".join(chosen.actions[:3]) + "."
        if fault.type == "cloud_cover":
            result = f"Grid draw now {fmt_kw(snap.grid_kw)}. No zone lost power."
        elif fault.type == "heatwave":
            result = f"Grid import now {fmt_kw(snap.grid_kw)}, peak kept under the contract limit. Comfort at {chosen.comfort}%."
        elif fault.type == "line_failure":
            z = next(z for z in snap.zones if z.id == (fault.target_zone_id or "hostel-gh1"))
            result = (f"{c.ZONE_BY_ID[z.id].name} back on at {fmt_kw(z.kw)}. Maintenance ticket raised for F3."
                      if z.kw > 0 else f"{c.ZONE_BY_ID[z.id].name} stays off until F3 is repaired. Ticket raised.")
        else:
            result = f"All zones powered from the battery ({round(self.grid.battery.soc_pct)}%)."
        return [
            {"id": "s5", "kind": "act", "agent": agent_act, "at": when, "summary": act},
            {"id": "s6", "kind": "result", "agent": "critic", "at": when, "summary": result + " Plan stored in the Critic's memory."},
        ]

    # ----- public API -----
    def step(self) -> dict:
        with self._lock:
            fault = self.grid.fault
            if fault:
                # One decision per incident: return it if it already exists.
                existing = next((x for x in self.decisions if x.get("incidentId") == fault.incident_id), None)
                if existing:
                    return existing
                d = self._scenario_decision(fault)
            else:
                d = self._routine_decision()
            self.decisions.insert(0, d)
            del self.decisions[30:]
            return d

    def respond(self, decision_id: str, response: dict) -> dict:
        with self._lock:
            d = next((x for x in self.decisions if x["id"] == decision_id), None)
            ctx = self.pending.pop(decision_id, None)
            if d is None or ctx is None:
                raise KeyError(decision_id)
            fault: Fault = ctx["fault"]
            chosen: Candidate = ctx["chosen"]
            kind = response.get("decision")
            when = iso(self.grid.now())
            if kind == "reject":
                self.grid.apply_policy(replace(chosen.policy, outage_hostel_level=0.5), mitigated=True)
                self.grid.set_mode("fallback")
                note, status = "Rejected by Duty Operator. Safe rule-based control is active (hostels at 50%).", "rejected"
                final = [
                    {"id": "s5", "kind": "act", "agent": "guardrail", "at": when, "summary": "Fallback rules applied: hostels at a fixed 50%."},
                    {"id": "s6", "kind": "result", "agent": "critic", "at": when, "summary": "All zones powered on safe rules. AI control can be resumed any time."},
                ]
            else:
                proposed = round(chosen.policy.outage_hostel_level, 2)
                level = float(response.get("optionId", proposed)) if kind == "modify" else proposed
                self.grid.apply_policy(replace(chosen.policy, outage_hostel_level=level), mitigated=True)
                pct = round(level * 100)
                runtime = self._outage_runtimes.get(level) or self._runtime_hours(replace(chosen.policy, outage_hostel_level=level))
                note = "Approved by Duty Operator." if kind == "approve" else f"Modified by Duty Operator: hostels at {pct}%."
                status = "approved" if kind == "approve" else "modified"
                final = [
                    {"id": "s5", "kind": "act", "agent": "orchestrator", "at": when, "summary": f"Hostels restored at {pct}%; battery powering the campus."},
                    {"id": "s6", "kind": "result", "agent": "critic", "at": when, "summary": f"All zones powered. Battery lasts ~{fmt_hours(runtime)} at this load."},
                ]
            d["steps"] = d["steps"] + final
            d["approval"] = {**d["approval"], "status": status,
                             "response": {**({"optionId": response.get("optionId")} if kind == "modify" else {}), "note": note, "at": when}}
            self.memory.record(fault, d)
            return d

    def set_goal(self, text: str) -> dict:
        with self._lock:
            self.goal = Goal.parse(text)
            self.grid.apply_policy(replace(self.grid.policy, reserve_floor_pct=self.goal.reserve_floor_pct), mitigated=False)
            if not self.grid.fault:
                # Re-plan straight away under the new goal; the decision shows up in the trace.
                self.decisions.insert(0, self._routine_decision())
                del self.decisions[30:]
            return {"goal": self.goal.text, "interpretation": self.goal.interpretation(), "acceptedAt": iso(self.grid.now())}

    def _learn_from_meters(self) -> None:
        """Once per sim hour: the Forecaster compares its old forecasts with what happened and learns."""
        if ml.FORECASTER is None:
            return
        hour = self._abs_hour()
        if self._last_observed_hour == hour:
            return
        self._last_observed_hour = hour
        g = self.grid
        cond = g.conditions(None)
        h = g.hour()
        ml.FORECASTER.observe(hour, g.snapshot().demand_kw, cond.solar_and_temp(h)[1], temps_ahead(cond, math.floor(h)))

    def tick(self) -> dict | None:
        """Called every few seconds: learns from the meters and re-plans when things have moved on."""
        with self._lock:
            try:
                self._learn_from_meters()
            except Exception:  # noqa: BLE001 - learning must never stop the control loop
                pass
            if self.grid.fault or self.pending:
                return None
            now = self.grid.hour()
            last = self._last_routine
            new_period = not last or last["period"] != period_of(now) or abs(now - last["hour"]) > 30
            hourly = last and now - last["hour"] >= 1.0
            temp_moved = last and abs(self.grid.environment()["temperatureC"] - last["temp"]) >= 1.5
            if not (new_period or hourly or temp_moved):
                return None
            d = self._routine_decision()
            if last and not new_period and self._last_routine["title"] == last.get("title") and not temp_moved:
                # Same plan as before: keep it running, no new trace entry.
                return None
            self.decisions.insert(0, d)
            del self.decisions[30:]
            return d

    def learning(self) -> dict:
        """What the agents have learned: trained models, live learning, and the Critic's memory."""
        f = ml.FORECASTER
        return {
            "trained": ml.METRICS,
            "live": {
                "forecasterOnlineUpdates": f.online_updates if f else 0,
                "forecasterLiveMaeKw": round(float(np.mean(f.live_errors)), 1) if f and f.live_errors else None,
                "memories": self.plans.summary()[-20:],
            },
            "available": {"forecaster": f is not None, "plannerPolicy": ml.PLANNER_Q is not None},
        }

    def agents(self) -> list[dict]:
        roles = {
            "orchestrator": ("Runs the decision loop, scores plans for your goal and explains every choice with the computed numbers.",
                             ["read_grid_state", "ask_forecaster", "request_plans", "submit_to_guardrail", "dispatch_action", "explain"]),
            "forecaster": ("A neural network trained on simulated campus history; predicts demand for the next 12 hours and keeps learning from the meters.",
                           ["learned_demand_forecast", "solar_forecast", "weather_feed", "learn_from_meters"]),
            "zone": ("One per building. Report load and how much can be safely reduced.", ["read_zone_meter", "set_hvac_setpoint", "report_flexibility"]),
            "planner": ("Invents plans by searching the available levers in the digital twin; one option is its own reinforcement-learning battery policy.",
                        ["cross_entropy_search", "simulate_in_twin", "rl_battery_policy", "compare_plans"]),
            "fault": ("Detects faults and isolates or reroutes power within seconds.", ["read_relays", "open_switch", "close_tie_switch"]),
            "critic": ("Remembers which plan worked in which situation and seeds later searches with it.",
                       ["score_outcome", "store_experience", "recall_similar_situation"]),
            "guardrail": ("Checks every plan against hard rules before anything happens.", ["check_rules", "require_approval", "veto"]),
        }
        last: dict[str, str] = {}
        for d in self.decisions:  # newest first
            for s in reversed(d["steps"]):
                last.setdefault(s["agent"], s["summary"])
        defaults = {"zone": "All buildings reporting normally.", "fault": "All feeders healthy."}
        waiting = bool(self.pending)
        out = []
        for aid, (role, tools) in roles.items():
            status = "waiting" if waiting and aid in ("orchestrator", "guardrail") else "idle"
            out.append({"id": aid, "name": AGENT_NAMES[aid], "role": role, "status": status,
                        "lastAction": last.get(aid, defaults.get(aid, "Standing by.")), "tools": tools})
        return out


def GUARDRAIL_FREE_TITLE(title: str) -> str:  # noqa: N802 - small helper used in lesson text
    return title[0].upper() + title[1:] if title else "This plan"
