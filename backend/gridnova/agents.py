"""The agents: observe -> reason -> plan (search in the twin) -> safety -> act -> learn.

Who does what, and what is learned rather than written by hand:

    Forecaster    a neural network trained on simulated campus history predicts the next 12 hours
                  of demand; it keeps learning online from the live meters (gridnova.ml.forecaster)
    Planner       invents plans by searching over the levers that are available (cross-entropy
                  search in the digital twin, gridnova.planning). One battery strategy it can pick
                  is its own reinforcement-learning policy (Q-learning, gridnova.ml.qagent)
    Guardrail     checks every plan's twin result against six hard rules; a failing plan is out
    Orchestrator  scores plans for the operator's goal, applies the winner, asks for approval
                  when many people are affected, and explains the choice with the computed numbers
    Critic        remembers which plan worked in which situation; similar situations later start
                  from that memory, so the search needs fewer twin runs (a faster response)

Nothing calls an external AI service. Explanations are sentences filled with the real numbers
the agents computed; they are not generated by a language model.
"""

